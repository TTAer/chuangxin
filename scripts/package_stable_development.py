"""Separate current development package from the immutable previous candidate."""
import hashlib
import json
from pathlib import Path
import zipfile
ROOT=Path(__file__).resolve().parents[1]
def load(p): return json.loads(p.read_text(encoding='utf-8'))
def digest(p): return hashlib.sha256(p.read_bytes()).hexdigest()
frozen=ROOT/'submission/graphschematic-association-20261005-frozen.zip'
with zipfile.ZipFile(frozen) as z:
    # Read the immutable archive itself; sidecar manifests may later be updated.
    names=set(json.loads(z.read('BUILD_MANIFEST.json'))['files'])
names.update(p.relative_to(ROOT).as_posix() for pattern in ('pcbparse/*.py','scripts/*.py','tests/*.py') for p in ROOT.glob(pattern))
names.update(['docs/STABLE_IDENTITY_AND_ELECTRICAL_GUARD.md','output/ablation/box-lifecycle.json','output/ablation/box-output-oracle.json','output/ablation/stable-live.json','output/ablation/stable-container.json','output/ablation/stable-image-sources.json','output/ablation/stable-export.json'])
for mode in ('stable-catalog','stable-transaction'):
    for domain in ('gt10','pcb55'): names.add('output/designator-'+mode+'/'+domain+'/summary.json')
proof=load(ROOT/'output/ablation/stable-container.json'); source=load(ROOT/'output/ablation/stable-image-sources.json')
assert proof['image_id']==source['image_id'] and source['source_and_selected_weights_match_workspace']
for name,sha in source['sha256'].items(): assert digest(ROOT/name)==sha,name
assert load(ROOT/'output/ablation/stable-live.json')['all_changed_pages_replayed']
manifest={'project':'GraphSchematic','artifact':'development candidate, not final competition submission','official_evaluator_verified':False,
          'current_container_image_id':proof['image_id'],'runtime_sources_and_selected_weights_match_container':True,
          'current_default_container_cases':1,'current_optional_container_cases':3,'current_image_batch_acceptance_verified':False,
          'historical_50_case_image':'sha256:e84d6832bc915cc3f584d4ad706fb6bc257d22cfe681b2fd2f0ea82e9475fab2',
          'frozen_previous_archive_sha256':digest(frozen),'default_designator_mode':'legacy','candidate_designator_mode':'stable','candidate_identity_transaction_mode':'catalog',
          'candidate_mean_pcb55':16.939932954100197,'candidate_mean_gt10':28.81555295769788,'candidate_pcb55_improved':9,'candidate_pcb55_regressed':1,
          'default_promoted':False,'function_tests_passed':99,'files':{},
          'limitations':['two development sets are reused, not blind tests','PCBnet autogenerated C_ keys are not always observable OCR designators','NetLineF1 decreased in guarded candidate','new image received four-case smoke validation; historical 50-case result belongs to frozen prior image']}
names.update(['output/ablation/stable-box-oracle.json','output/ablation/stable-physical-audit.json','output/ablation/stable-visible-unassigned.json','output/ablation/proxy-conflict-cases.json'])
for name in sorted(names):
    p=ROOT/name; assert p.is_file(),name
    manifest['files'][name]={'bytes':p.stat().st_size,'sha256':digest(p)}
out=ROOT/'submission/graphschematic-stable-development.zip'
with zipfile.ZipFile(out,'w',zipfile.ZIP_DEFLATED) as z:
    for name in sorted(names): z.write(ROOT/name,name)
    z.writestr('BUILD_MANIFEST.json',json.dumps(manifest,indent=2))
out.with_suffix('.manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
print(json.dumps({'archive':str(out),'sha256':digest(out),'files':len(names),'bytes':out.stat().st_size},ensure_ascii=False),flush=True)
